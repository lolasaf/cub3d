void	print_poki(t_game *game)
{
	static int	collected = 0;

	collected++;
	printf("\033[35m");
	printf("++++-+-+-+-+-+-+-+-+-+ +--+ +-+-+-+-+-+ ++ +-+-+-+-+-+ +--++++\n");
	printf("+++|C|o|l|l|e|c|t|e|d| |%02d| |P|o|k|i|s| || |L|e|f|t|:| ",
		collected);
	printf("|%02d|+++\n", game->num_sprites - collected);
	printf("++++-+-+-+-+-+-+-+-+-+ +--+ + +-+-+-+-+ ++ +-+-+-+-+-+ +--++++\n");
	printf("\033[0m");
}

